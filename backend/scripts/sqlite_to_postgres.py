"""One-way export of the SQLite stores into a PostgreSQL migration script.

The runtime still uses SQLite: this script moves *data* into PostgreSQL so it
can be inspected, queried or used by a future adapter. It does not translate
the application's `?` placeholders, upserts or locking, so pointing the app at
PostgreSQL still requires the adapter work described in
`docs/postgres-migration.md`.

Usage:
    python backend/scripts/sqlite_to_postgres.py --out migration.sql

Each SQLite file becomes its own PostgreSQL schema (scenarios, game_state,
events, traces) so table-name collisions are avoided.
"""
from __future__ import annotations

import argparse
import os
import sqlite3
from pathlib import Path
from typing import Iterable, Sequence, Tuple

DEFAULT_SOURCES: Sequence[Tuple[str, str]] = (
    ("scenarios", "scenarios.db"),
    ("game_state", "game_state.db"),
    ("events", "events.db"),
    ("traces", "traces.db"),
)


def _quote(value) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bytes):
        return "'\\x" + value.hex() + "'"
    if isinstance(value, bool):
        return "TRUE" if value else "FALSE"
    if isinstance(value, (int, float)):
        return repr(value)
    text = str(value).replace("'", "''")
    return "'" + text + "'"


def _translate_ddl(table: str, schema: str, sql: str, tables: Iterable[str]) -> str:
    translated = sql.replace(f"CREATE TABLE {table}", f"CREATE TABLE {schema}.{table}", 1)
    for other in tables:
        translated = translated.replace(
            f"REFERENCES {other}(", f"REFERENCES {schema}.{other}("
        )
    translated = translated.replace("REAL", "DOUBLE PRECISION")
    translated = translated.replace("BLOB", "BYTEA")
    translated = translated.replace("INTEGER PRIMARY KEY", "BIGINT PRIMARY KEY")
    return translated + ";"


def schema_sql(schema: str, path: str | Path) -> str:
    connection = sqlite3.connect(str(path))
    try:
        tables = [
            row[0]
            for row in connection.execute(
                "SELECT name FROM sqlite_master WHERE type='table' ORDER BY name"
            )
            if not row[0].startswith("sqlite_")
        ]
        parts = [f'CREATE SCHEMA IF NOT EXISTS "{schema}";']
        for table in tables:
            ddl = connection.execute(
                "SELECT sql FROM sqlite_master WHERE type='table' AND name=?", (table,)
            ).fetchone()
            if not ddl or not ddl[0]:
                continue
            parts.append(_translate_ddl(table, schema, ddl[0], tables))
            columns = [
                row[1]
                for row in connection.execute(f'PRAGMA table_info("{table}")')
            ]
            rows = connection.execute(
                f'SELECT {", ".join(columns)} FROM "{table}"'
            ).fetchall()
            if rows:
                quoted_columns = ", ".join(f'"{column}"' for column in columns)
                values = ",\n    ".join(
                    "(" + ", ".join(_quote(value) for value in row) + ")" for row in rows
                )
                parts.append(
                    f'INSERT INTO {schema}.{table} ({quoted_columns}) VALUES\n    {values};'
                )
        return "\n\n".join(parts)
    finally:
        connection.close()


def build_sql(sources: Sequence[Tuple[str, str | Path]]) -> str:
    sections = [
        "-- Generated by backend/scripts/sqlite_to_postgres.py",
        "-- Runtime adapter is not included; see docs/postgres-migration.md.",
        "BEGIN;",
    ]
    for schema, path in sources:
        if not os.path.exists(path):
            sections.append(f"-- skipped missing source {path}")
            continue
        sections.append(f'-- source: {path}')
        sections.append(schema_sql(schema, path))
    sections.append("COMMIT;")
    return "\n\n".join(sections) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    base = Path(__file__).resolve().parent.parent
    parser.add_argument("--out", required=True, help="output .sql file")
    parser.add_argument("--scenarios", default=str(base / "scenarios.db"))
    parser.add_argument("--game-state", default=str(base / "game_state.db"))
    parser.add_argument("--events", default=str(base / "events.db"))
    parser.add_argument("--traces", default=str(base / "traces.db"))
    args = parser.parse_args()
    sources = (
        ("scenarios", args.scenarios),
        ("game_state", args.game_state),
        ("events", args.events),
        ("traces", args.traces),
    )
    Path(args.out).write_text(build_sql(sources), encoding="utf-8")
    print(f"wrote {args.out}")


if __name__ == "__main__":
    main()
